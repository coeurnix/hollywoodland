// Talent trees, tiers 1-2 (DESIGN-BIBLE §5: one point per level from 10, 3 trees x 16, a tier opens every 5 points
// spent in that tree). The slice ships the first two tiers of every tree: 2 talents per tier, 4 per tree, 96 in all.
// Talents are passive modifiers; `mods` gives the value per rank. The client applies them generically:
//   str_pct agi_pct sta_pct int_pct spi_pct    attribute +%            hp_pct res_pct       max health / Power +%
//   crit dodge parry block                     flat chance (0.01 = 1%)  armor_pct            armour +%
//   dmg_pct heal_pct taken_pct threat_pct      done / healing / taken / threat +%  speed_pct  run speed +%
//   ab:<ability id>  that ability's damage, healing or absorb +%      cost:<ability id>  its cost -%
//   cd:<ability id>  its cooldown, seconds shorter                      regen_pct  Power, Energy, Focus regeneration +%
const T = (cls, spec, tier, col, id, name, ranks, mods) => ({ id: `tal_${id}`, name, class: cls, spec, tier, col, ranks, mods, desc: '' });

