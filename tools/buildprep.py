"""Stage the published building kit (art/buildings/manifest.json, from the building-art agent) for import into /Game/Buildings.

    python -I tools/buildprep.py            then   hollywoodland-ue\\Scripts\\ImportBuildings.ps1

Only assets indexed in the manifest are staged. The FBX files are already game-ready (metres, +Z up, -Y front, one material,
triangulated), so meshes are copied as they are; textures are resized for the web budget:
  family atlases and landmarks 2048 (they carry whole facades), sign pages and tileables 1024.
Writes:
  hollywoodland-ue/Saved/BuildStage/stage.json     the import list (same format as tools/propprep.py's PropStage)
  hollywoodland-ue/Content/Data/buildings.json     runtime table: id -> mesh path, kind, nominal size, recipe data
                                                   (bounds are filled in by the import, like props.json)
"""
import json
import os
import shutil
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'art', 'buildings')
STAGE = os.path.join(ROOT, 'hollywoodland-ue', 'Saved', 'BuildStage')
TABLE = os.path.join(ROOT, 'hollywoodland-ue', 'Content', 'Data', 'buildings.json')
BASE = '/Game/Buildings'
SIZE = {'atlas': 2048, 'landmark': 2048, 'sign': 1024, 'tile': 1024}


def tex_name(path):
    return os.path.splitext(os.path.basename(path))[0]


def stage_texture(path, kind, done, out):
    name = tex_name(path)
    if name in done:
        return name
    dst = os.path.join(STAGE, 'Tex', name + '.png')
    im = Image.open(os.path.join(SRC, path)).convert('RGB')
    n = SIZE[kind]
    if im.width > n:
        im = im.resize((n, n), Image.LANCZOS)
    im.save(dst)
    done.add(name)
    out.append({'file': dst, 'name': name, 'kind': 'B'})
    return name


def main():
    m = json.load(open(os.path.join(SRC, 'manifest.json'), encoding='utf-8'))
    if m.get('units') != 'meters' or m.get('up') != '+Z' or m.get('front') != '-Y':
        sys.exit('manifest conventions changed; review before importing')
    for d in ('Tex', 'Mesh'):
        os.makedirs(os.path.join(STAGE, d), exist_ok=True)
    textures, meshes, done = [], [], set()
    old = json.load(open(TABLE)) if os.path.exists(TABLE) else {'props': {}}
    table = {'note': 'Generated by tools/buildprep.py from art/buildings/manifest.json; min/max (metres, front +X) by Scripts/ImportBuildings.ps1.',
             'props': {}, 'recipes': m.get('recipes', {}), 'signs': {s['id']: s for s in m.get('signs', [])}}
    for a in m['assets']:
        t = a['texture']
        if t.startswith('atlas:'):
            t, kind = m['atlases'][t[6:]]['texture'], 'atlas'
        elif a['kind'] == 'sign_card':
            kind = 'sign'
        elif a['kind'] in ('wall', 'roof'):
            kind = 'tile'
        else:
            kind = 'landmark'
        tn = stage_texture(t, kind, done, textures)
        src = os.path.join(SRC, a['file'])
        dst = os.path.join(STAGE, 'Mesh', f"SM_{a['id']}.fbx")
        shutil.copyfile(src, dst)
        mat = f"MI_{tn[2:] if tn.startswith('T_') else tn}"
        meshes.append({'file': dst, 'name': f"SM_{a['id']}", 'material': mat, 'tex': {'B': tn}})
        e = {'mesh': f"{BASE}/SM_{a['id']}.SM_{a['id']}", 'kind': a['kind'], 'nominal': a.get('nominal'), 'tris': a.get('tris'),
             'origin': a.get('origin'), 'attachments': a.get('attachments', [])}
        prev = old['props'].get(a['id'], {})
        if 'min' in prev:
            e['min'], e['max'] = prev['min'], prev['max']
        table['props'][a['id']] = e
    uniq = meshes  # meshes sharing a texture share its material instance (the importer makes each instance once)
    json.dump({'textures': textures, 'meshes': uniq, 'base': BASE, 'table': TABLE}, open(os.path.join(STAGE, 'stage.json'), 'w'), indent=1)
    json.dump(table, open(TABLE, 'w'), indent=1)
    print(f'buildprep: {len(uniq)} meshes, {len(textures)} textures -> {STAGE}; table {os.path.relpath(TABLE, ROOT)}')


if __name__ == '__main__':
    main()
